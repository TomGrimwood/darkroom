"""A capture's look as ovrtx takes it: Kit settings turned into the attributes ovrtx's own
schemas say stand for them, each on the camera or on its render product as its schema is for."""

from darkroom.ovrtx import settings

SCHEMA = '''#usda 1.0

class "OmniRtxCameraAutoExposureAPI_1"
{
    bool omni:rtx:autoExposure:enabled = 0 (
        doc = """Enables auto-exposure on this camera.
        (deprecated carb setting path: '/rtx/post/histogram/enabled')"""
    )
}

class "OmniRtxSettingsRtAPI_1"
{
    float omni:rtx:rt:ambientLight:intensity = 1 (
        doc = "(deprecated carb setting path: '/rtx/sceneDb/ambientLightIntensity')"
    )
    uint omni:rtx:rtpt:maxBounces = 3 (
        doc = "(deprecated carb setting path: '/rtx/rtpt/maxBounces')"
    )
    color3f omni:rtx:rt:ambientLight:color = (0.1, 0.1, 0.1) (
        doc = "(deprecated carb setting path: '/rtx/sceneDb/ambientLightColor')"
    )
}

class "OmniRtxPostTonemapAPI_1"
{
    token omni:rtx:post:tonemap:operator = "acesApproximation" (
        doc = "(deprecated carb setting path: '/rtx/post/tonemap/op')"
    )
    float omni:rtx:post:motionblur:maxBlurDiameterFraction = 0.02
}

class "OmniRtxSettingsGlobalCommonAPI_1"
{
    bool omni:rtx:global:something = 0 (
        doc = "(deprecated carb setting path: '/rtx/global/something')"
    )
}
'''
PLUG_INFO = """# Portions of this file auto-generated by usdGenSchema.
{
    "Plugins": [{"Info": {
        "AutoApplyAPISchemas": {
            "OmniRtxSettingsRtAPI_1": {"apiSchemaAutoApplyTo": ["RenderProduct"]},
            "OmniRtxSettingsGlobalCommonAPI_1": {"apiSchemaAutoApplyTo": ["RenderSettings"]}
        },
        "Types": {
            "RtxSettingsOmniRtxCameraAutoExposureAPI_1": {
                "alias": {"UsdSchemaBase": "OmniRtxCameraAutoExposureAPI_1"},
                "apiSchemaCanOnlyApplyTo": ["Camera"]
            },
            "RtxSettingsOmniRtxPostTonemapAPI_1": {
                "alias": {"UsdSchemaBase": "OmniRtxPostTonemapAPI_1"},
                "apiSchemaCanOnlyApplyTo": ["RenderProduct"]
            }
        }
    }}]
}
"""


def _schemas(tmp_path):
    (tmp_path / "generatedSchema.usda").write_text(SCHEMA, encoding="utf-8")
    (tmp_path / "plugInfo.json").write_text(PLUG_INFO, encoding="utf-8")
    return settings.read([tmp_path / "generatedSchema.usda"])


def test_schemas_say_which_attribute_stands_for_a_setting_and_what_prim_it_is_for(tmp_path):
    schemas = _schemas(tmp_path)
    assert schemas.by_setting["/rtx/rtpt/maxBounces"] == [
        ("OmniRtxSettingsRtAPI_1", "omni:rtx:rtpt:maxBounces", "uint")
    ]
    assert schemas.on["OmniRtxCameraAutoExposureAPI_1"] == "Camera"
    assert schemas.on["OmniRtxSettingsRtAPI_1"] == "RenderProduct"
    assert schemas.by_attribute["omni:rtx:autoExposure:enabled"][0].startswith("OmniRtxCamera")


def test_a_look_becomes_attributes_on_the_camera_and_on_its_render_product(tmp_path):
    from pxr import Gf

    look = {
        "/rtx/post/histogram/enabled": False,
        "/rtx/sceneDb/ambientLightIntensity": 0,
        "rtx/rtpt/maxBounces": 6,  # with or without its first slash
        "/rtx/sceneDb/ambientLightColor": [0.5, 0.25, 1.0],
        "/rtx/post/tonemap/op": 6,  # Kit's index: ovrtx names it, so left out
        "/rtx/global/something": True,  # render-wide: no camera's, no render product's
        "/rtx/unknown": 1,
    }
    made = settings.translate(look, _schemas(tmp_path))
    assert made.camera == {"omni:rtx:autoExposure:enabled": ("bool", False)}
    assert made.product == {
        "omni:rtx:rt:ambientLight:intensity": ("float", 0.0),
        "omni:rtx:rtpt:maxBounces": ("uint", 6),
        "omni:rtx:rt:ambientLight:color": ("color3f", Gf.Vec3f(0.5, 0.25, 1.0)),
    }
    assert made.left == ("/rtx/post/tonemap/op", "/rtx/global/something", "/rtx/unknown")


def test_a_cameras_own_rtx_settings_stay_on_it_or_go_on_its_render_product(tmp_path):
    own = {
        "omni:rtx:autoExposure:enabled": ("bool", True),
        "omni:rtx:post:motionblur:maxBlurDiameterFraction": ("float", 0.05),
        "omni:rtx:not:in:any:schema": ("int", 1),
    }
    made = settings.split(own, _schemas(tmp_path))
    assert list(made.camera) == ["omni:rtx:autoExposure:enabled"]
    assert list(made.product) == [
        "omni:rtx:post:motionblur:maxBlurDiameterFraction",
        "omni:rtx:not:in:any:schema",
    ]


def test_a_spans_look_is_time_sampled_from_its_start_to_its_end_then_back(tmp_path):
    """A span's attributes as time codes (60 a second): the camera's own value before and
    after, the span's within; with none of its own, its schema's default; one the span alone
    names is set on the side its schema is for."""
    schemas = _schemas(tmp_path)
    spans = [
        (1.0, 2.0, settings.translate({"/rtx/rtpt/maxBounces": 8}, schemas)),
        (3.0, 3.5, settings.translate({"/rtx/post/histogram/enabled": True}, schemas)),
    ]
    own = {"omni:rtx:rtpt:maxBounces": ("uint", 4)}
    product = settings.samples(spans, "product", own, schemas, 60.0, 1 / 60)
    kind, keys = product["omni:rtx:rtpt:maxBounces"]
    assert kind == "uint"
    # the span's 8 from half a step before code 60 to half a step before 120, the product's
    # own 4 either side of it
    assert [(round(c, 3), v) for c, v in keys] == [
        (59.499, 4), (59.5, 8), (119.499, 8), (119.5, 4),
        (179.499, 4), (179.5, 4), (209.499, 4), (209.5, 4),
    ]  # fmt: skip
    camera = settings.samples(spans, "camera", {}, schemas, 60.0, 1 / 60)
    kind, keys = camera["omni:rtx:autoExposure:enabled"]
    assert kind == "bool"
    assert [v for c, v in keys if 179.5 <= c < 209.5] == [True, True]  # the schema's 0 outside
    assert [v for c, v in keys if c < 179.5 or c >= 209.5] == [0] * 6
